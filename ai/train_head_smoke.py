"""Run a short, local head-detector fine-tuning check and save validation predictions."""

import argparse
import csv
import hashlib
import json
import math
import os
import time
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=ROOT / "data/head_cafeteria_v1/data.yaml")
    parser.add_argument("--model", type=Path, default=ROOT / "weights/yolov8n.pt")
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--imgsz", type=int, default=1280)
    parser.add_argument("--batch", type=int, default=2)
    parser.add_argument("--lr0", type=float, default=0.001, help="Initial learning rate for this fine-tuning run")
    parser.add_argument("--save-period", type=int, default=-1,
                        help="Save an intermediate checkpoint every N epochs; -1 disables, 1 saves every epoch")
    parser.add_argument("--device", choices=("mps", "cpu"), default="mps")
    parser.add_argument("--name", default=datetime.now(timezone.utc).strftime("smoke_%Y%m%dT%H%M%SZ"))
    args = parser.parse_args()
    if min(args.epochs, args.imgsz, args.batch) < 1 or Path(args.name).name != args.name or args.name in (".", ".."):
        parser.error("Use positive epochs/imgsz/batch and a single directory name.")
    if not math.isfinite(args.lr0) or args.lr0 <= 0:
        parser.error("--lr0 must be positive and finite.")
    if args.save_period != -1 and args.save_period < 1:
        parser.error("--save-period must be -1 or a positive integer.")
    args.data, args.model = args.data.expanduser().resolve(), args.model.expanduser().resolve()
    if not args.data.is_file() or not args.model.is_file():
        parser.error("A local data YAML and a downloaded local checkpoint are required.")
    output = ROOT / "runs/head" / args.name
    if output.exists():
        parser.error(f"Output already exists; use a new --name: {output}")

    # Keep this run local, including its settings and plotting cache.
    os.environ["YOLO_OFFLINE"] = "true"
    os.environ["YOLO_AUTOINSTALL"] = "false"
    os.environ["YOLO_CONFIG_DIR"] = str(ROOT / "runs/.ultralytics")
    os.environ["MPLCONFIGDIR"] = str(ROOT / "runs/.matplotlib")
    os.environ.pop("ULTRALYTICS_API_KEY", None)
    for directory in ("YOLO_CONFIG_DIR", "MPLCONFIGDIR"):
        Path(os.environ[directory]).mkdir(parents=True, exist_ok=True)

    import torch
    import ultralytics
    import yaml
    from ultralytics import YOLO
    if __package__:
        from .mps_head_runtime import MPSHeadTrainer, MPSHeadPredictor
    else:
        from mps_head_runtime import MPSHeadTrainer, MPSHeadPredictor

    ultralytics.settings.update({
        "sync": False, "hub": False, "api_key": "", "clearml": False,
        "comet": False, "dvc": False, "mlflow": False, "neptune": False,
        "raytune": False, "tensorboard": False, "wandb": False,
    })
    if args.device == "mps" and not torch.backends.mps.is_available():
        raise RuntimeError("MPS is unavailable in this process; CPU fallback was not requested.")
    data = yaml.safe_load(args.data.read_text())
    if data.get("names") not in ({0: "head"}, {"0": "head"}, ["head"]):
        raise ValueError("Expected one class: 0=head")
    dataset_root = Path(data["path"])
    if not dataset_root.is_absolute():
        raise ValueError("Use an absolute dataset path, as generated by prepare_head_dataset.py.")
    if "download" in data:
        raise ValueError("This local smoke runner does not accept dataset download instructions.")
    dataset_counts = {}
    for split in ("train", "val"):
        image_dir = dataset_root / data[split]
        label_dir = dataset_root / f"labels/{split}"
        if not image_dir.is_dir() or not label_dir.is_dir():
            raise ValueError("Expected prepared image directories with labels/train and labels/val.")
        image_files = sorted(image_dir.glob("*.jpg"))
        if not image_files:
            raise ValueError(f"No prepared JPEG images in {image_dir}")
        box_count = sum(len([line for line in (label_dir / image.with_suffix(".txt").name).read_text().splitlines() if line.strip()]) for image in image_files)
        dataset_counts[split] = {"images": len(image_files), "boxes": box_count}

    model = YOLO(str(args.model), task="detect")
    started = time.perf_counter()
    metrics = model.train(
        trainer=MPSHeadTrainer,
        data=str(args.data), device=args.device, epochs=args.epochs, imgsz=args.imgsz,
        batch=args.batch, workers=0, cache=False, amp=False, seed=0,
        optimizer="AdamW", lr0=args.lr0, lrf=0.1, nbs=args.batch, warmup_epochs=0,
        mosaic=0, close_mosaic=0, scale=0.1, translate=0.05,
        plots=True, save=True, save_period=args.save_period, val=True,
        project=str(output.parent), name=args.name,
        exist_ok=False,
    )
    training_seconds = time.perf_counter() - started
    output = Path(model.trainer.save_dir)
    best = output / "weights/best.pt"
    last = output / "weights/last.pt"
    if not best.is_file() or not last.is_file():
        raise RuntimeError("Training did not produce both best.pt and last.pt.")
    with (output / "results.csv").open() as result_file:
        rows = list(csv.DictReader(result_file))
    if len(rows) != args.epochs:
        raise RuntimeError(f"Expected {args.epochs} epochs; found {len(rows)}.")
    if not all(math.isfinite(float(value)) for row in rows for value in row.values()):
        raise RuntimeError("Training results contain a non-finite value.")
    epoch_checkpoints = []
    if args.save_period > 0:
        # Ultralytics 8.3.253 uses zero-based epoch numbers in checkpoint filenames.
        for index in range(0, len(rows), args.save_period):
            checkpoint = output / f"weights/epoch{index}.pt"
            if not checkpoint.is_file():
                raise RuntimeError(f"Missing intermediate checkpoint: {checkpoint}")
            epoch_checkpoints.append({"completed_epochs": index + 1, "file": str(checkpoint)})

    detector = YOLO(str(best), task="detect")
    if detector.names != {0: "head"}:
        raise RuntimeError(f"Unexpected trained classes: {detector.names}")
    predictions = []
    for result in detector.predict(
        predictor=MPSHeadPredictor,
        source=str(dataset_root / data["val"]), device=args.device,
        imgsz=args.imgsz, conf=0.25, iou=0.7, max_det=300,
        save=True, save_txt=True, save_conf=True, stream=True,
        project=str(output), name="predictions", exist_ok=False,
    ):
        source = Path(result.path)
        label = dataset_root / "labels/val" / source.with_suffix(".txt").name
        truth_count = len([row for row in label.read_text().splitlines() if row.strip()])
        predictions.append({
            "image": source.name, "ground_truth_heads": truth_count,
            "predicted_heads": len(result.boxes),
            "boxes_xyxy": result.boxes.xyxy.cpu().tolist(),
            "confidence": result.boxes.conf.cpu().tolist(),
        })
    summary = {
        "purpose": "Short fine-tuning execution check, not a production accuracy claim",
        "initial_model": str(args.model),
        "initial_model_sha256": hashlib.sha256(args.model.read_bytes()).hexdigest(),
        "initial_model_source": "Existing local checkpoint identified by initial_model and initial_model_sha256",
        "data": str(args.data), "dataset_counts": dataset_counts,
        "device": str(model.trainer.device),
        "mps_postprocessing": "CPU NMS per image; model training/inference stays on MPS",
        "ultralytics_version": ultralytics.__version__, "torch_version": torch.__version__,
        "epochs": len(rows), "initial_learning_rate": args.lr0,
        "save_period": args.save_period, "epoch_checkpoints": epoch_checkpoints,
        "training_and_validation_seconds": training_seconds,
        "all_logged_values_finite": True, "classes": detector.names,
        "metrics_on_validation": {key: float(value) for key, value in metrics.results_dict.items()},
        "prediction_confidence_threshold": 0.25, "validation_predictions": predictions,
        "count_mean_absolute_error_at_025": sum(abs(p["predicted_heads"] - p["ground_truth_heads"]) for p in predictions) / len(predictions),
        "best": str(best), "last": str(last),
        "limitations": ["This runner evaluates the validation split, not an independent test set.",
                        "Data volume and scene coverage must be checked before interpreting accuracy.",
                        "warmup_epochs=0 and nbs=batch are explicit short-run choices, not tuned production settings.",
                        "Count agreement alone does not establish correct object localization."],
    }
    (output / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"output": str(output), "summary": str(output / "summary.json")}, ensure_ascii=False))


if __name__ == "__main__":
    main()
